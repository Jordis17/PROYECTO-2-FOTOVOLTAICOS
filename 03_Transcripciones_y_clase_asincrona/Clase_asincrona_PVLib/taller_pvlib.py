def get_irradiance(site_location, start, end, tilt, surface_azimuth):
    # Creates one day's worth of 1min intervals
    times = pd.date_range(start, end, freq='1min', tz=site_location.tz)

    # Generate clearsky data using the Ineichen model, which is the default
    # The get_clearsky method returns a dataframe with values for GHI, DNI, and DHI
    clearsky = site_location.get_clearsky(times)

    # Get solar azimuth and zenith to pass to the transposition function
    solar_position = site_location.get_solarposition(times=times)

    # Use the get_total_irradiance function to transpose the GHI to POA
    POA_irradiance = irradiance.get_total_irradiance(
        surface_tilt = tilt,
        surface_azimuth = surface_azimuth,
        dni = clearsky['dni'],
        ghi = clearsky['ghi'],
        dhi = clearsky['dhi'],
        solar_zenith = solar_position['apparent_zenith'],
        solar_azimuth = solar_position['azimuth'])

    # Return DataFrame with only GHI and POA
    return pd.DataFrame({'DNI': clearsky['dni'],
                    'DHI': clearsky['dhi'],
                    'GHI': clearsky['ghi'],
                    'POA': POA_irradiance['poa_global']})

